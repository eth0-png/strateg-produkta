# Расчёты по числам брифа (S-1). Единицы: млн руб., штуки групп, штуки оплаченных месяцев номера.
# Ставка 500 руб. валовой прибыли за один дополнительный оплаченный месяц одного номера (бриф).
# Допущения помечены ДОПУЩЕНИЕ, значения подлежат проверке в пилоте.
import math

RATE = 500.0
print("== Зазор по прибыли ==")
base_noch, goal, base_est = 279.0, 285.0, 275.0
gap = goal - base_noch
print(f"Зазор до цели при обычном обслуживании: {gap:.0f} млн руб.")
months_needed = gap * 1_000_000 / RATE
print(f"Нужно дополнительных оплаченных месяцев при ставке 500 руб. и без новых расходов: {months_needed:.0f}")
print(f"Плановый год без изменений против оценки базового года: {base_noch - base_est:+.0f} млн руб.")

print("\n== Сколько номеров нужно при разной длительности удержания (без прямых расходов) ==")
for m in (1, 2, 3, 4, 6, 9, 12):
    print(f"  +{m} мес. на номер: нужно {months_needed / m:.0f} номеров")
print("  Работа, начатая в последнем месяце года, даёт не больше одного месяца на номер (бриф).")

print("\n== Если появляются новые прямые расходы d руб. за доп. месяц ==")
for d in (0, 50, 100, 150, 200):
    net = RATE - d
    print(f"  расходы {d} руб. на доп. месяц: нужно {gap * 1_000_000 / net:.0f} месяцев")

print("\n== Семейные группы (бриф) ==")
conn_start, conn_noch, conn_goal = 6500, 8000, 12000
act_noch, act_goal = 5000, 8000
print(f"Прирост подключённых: цель {conn_goal - conn_start}, без изменений {conn_noch - conn_start}, разрыв {conn_goal - conn_noch}")
print(f"Доля активных среди подключённых: без изменений {act_noch / conn_noch:.1%}, цель при 12000 подключённых: {act_goal / conn_goal:.1%}")
for share in (0.60, 0.625, 0.65, 0.667, 0.70):
    print(f"  при 12000 подключённых и доле активных {share:.1%}: активных {conn_goal * share:.0f}")
need_conn = act_goal / (act_noch / conn_noch)
print(f"  чтобы получить 8000 активных при доле {act_noch / conn_noch:.1%}, нужно подключённых {need_conn:.0f}")
print("  Если доля активных растёт до 70 %, подключённых нужно:", f"{act_goal / 0.70:.0f}")
print("  Если подключённых 10000 (часть цели), доля активных для 8000:", f"{act_goal / 10000:.1%}")

print("\n== Активация за 14 дней (бриф) ==")
for rate in (0.42, 0.45, 0.50, 0.60):
    print(f"  доля {rate:.0%} при 100 созданных группах: {rate * 100:.0f} активированных")
print(f"  Цель 60 % против 45 % без изменений: +{(0.60 - 0.45) * 100:.0f} п.п., относительно {(0.60 / 0.45 - 1):.1%}")

print("\n== Владельцы нескольких номеров (бриф) ==")
print(f"Цель 2000 против 1000 без изменений: разрыв 1000. Доля от доступной базы 40000: цель {2000 / 40000:.1%}, без изменений {1000 / 40000:.1%}, оценка базового года {800 / 40000:.1%}")
print(f"Семьи: доступная база 100000 домохозяйств, цель {12000 / 100000:.1%}, без изменений {8000 / 100000:.1%}, начало года {6500 / 100000:.1%}")

print("\n== Вклад одной семейной группы при удержании (ДОПУЩЕНИЕ: номеров в группе n, доп. месяцев m) ==")
for n in (2, 3, 4):
    for m in (1, 2, 3):
        print(f"  группа из {n} номеров, +{m} мес.: {n * m * RATE:.0f} руб. на группу")
print("  Групп с доп. месяцами при группе из 3 номеров и +2 мес. нужно для закрытия зазора:", f"{months_needed / (3 * 2):.0f}")
print("  Групп с доп. месяцами при группе из 3 номеров и +1 мес. нужно:", f"{months_needed / 3:.0f}")

print("\n== Размер пилота: сравнение долей двух групп (мощность 80 %, уровень 5 %, двусторонний) ==")
za, zb = 1.96, 0.84
def n_arm(p1, p2):
    return math.ceil(((za + zb) ** 2) * (p1 * (1 - p1) + p2 * (1 - p2)) / (p1 - p2) ** 2)
for p1, p2 in ((0.12, 0.09), (0.12, 0.08), (0.12, 0.06), (0.20, 0.15), (0.20, 0.10)):
    n = n_arm(p1, p2)
    print(f"  доля {p1:.0%} против {p2:.0%}: на группу сравнения {n}, всего {2 * n}")

print("\n== Темп набора (ДОПУЩЕНИЕ: подходящих новых групп в неделю w, недель набора t) ==")
for w in (25, 50, 100, 200):
    for need in (600, 3266):
        print(f"  {w} групп в неделю: {need} групп набирается за {need / w:.1f} недель")
print("  Пример из брифа: 600 групп за 6 недель = 100 групп в неделю.")
print("  Прирост подключённых групп без изменений за год: ", f"{conn_noch - conn_start} (в среднем {(conn_noch - conn_start) / 52:.0f} в неделю, чистый прирост без учёта выбытия)")

print("\n== Предельное вложение при окупаемости за T кварталов (ДОПУЩЕНИЕ: допмесяцы m_q по кварталам) ==")
# вклад 500 руб. за месяц; ДОПУЩЕНИЕ: прирост в оплаченных месяцах за квартал после запуска во 2-м квартале
scenarios = {"низкий": (0, 1000, 2500, 3500), "базовый": (0, 3000, 6000, 8000), "высокий": (0, 5000, 10000, 14000)}
for name, q in scenarios.items():
    cum = 0
    row = []
    for i, mnths in enumerate(q, 1):
        cum += mnths * RATE
        row.append(f"К{i}: {cum / 1e6:.2f} млн")
    print(f"  {name} (доп. месяцев по кварталам {q}): накопленная прибыль до расходов на обслуживание: " + "; ".join(row))
    print(f"      в плановом году всего месяцев: {sum(q)}, прибыль {sum(q) * RATE / 1e6:.2f} млн, зазор 6 млн закрыт: {sum(q) >= months_needed}")
