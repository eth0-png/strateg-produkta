# Сравнение вариантов по вкладу в зазор 6 млн руб. (числа брифа S-1, расчёт S-25).
# ДОПУЩЕНИЯ помечены, значения проверяются журналом случаев и пилотом.
RATE = 500.0
GAP_MONTHS = 12000  # бриф и S-25

# Средняя база за год по брифу: семьи 6 500 на начало и 8 000 на конец, владельцы 800 и 1 000.
fam_groups = (6500 + 8000) / 2
own_people = (800 + 1000) / 2
print(f"Средняя база за год: семейных групп {fam_groups:.0f}, владельцев {own_people:.0f}")

# ДОПУЩЕНИЕ: номеров в семейной группе и у владельца
fam_n = {"мало": 2.5, "средне": 3.0, "много": 3.5}
own_n = {"мало": 2.0, "средне": 2.5, "много": 3.0}

def factor(m):
    # снижение месячного оттока на d сохраняет d номеров каждый месяц, сохранённые копятся: сумма 1..m
    return m * (m + 1) / 2

print("\n== Номеров в охвате ==")
for k in fam_n:
    print(f"  семьи, {k} ({fam_n[k]} номера в группе): номеров {fam_groups * fam_n[k]:.0f}")
for k in own_n:
    print(f"  владельцы, {k} ({own_n[k]} номера): номеров {own_people * own_n[k]:.0f}")

print("\n== Доп. оплаченные месяцы за плановый год при снижении месячного оттока на d п.п. ==")
print("  (ДОПУЩЕНИЕ: эффект с начала 2-го квартала это 9 месяцев, с начала 3-го квартала это 6 месяцев)")
for m in (9, 6):
    for d in (0.5, 1.0, 2.0):
        f_ = fam_groups * fam_n["средне"] * d / 100 * factor(m)
        o_ = own_people * own_n["средне"] * d / 100 * factor(m)
        print(f"  {m} мес., d={d} п.п.: семьи {f_:.0f} мес. ({f_ * RATE / 1e6:.2f} млн), владельцы {o_:.0f} мес. ({o_ * RATE / 1e6:.2f} млн)")

print("\n== Какое снижение оттока закрывает зазор 12 000 месяцев (средние допущения) ==")
for m in (9, 6):
    fd = GAP_MONTHS / (fam_groups * fam_n["средне"] * factor(m)) * 100
    od = GAP_MONTHS / (own_people * own_n["средне"] * factor(m)) * 100
    print(f"  эффект {m} мес.: семьи {fd:.1f} п.п. в месяц, владельцы {od:.1f} п.п. в месяц")

print("\n== Потолок владельцев: все номера владельцев на все месяцы эффекта ==")
for m in (9, 6):
    cap = own_people * own_n["много"] * m
    print(f"  эффект {m} мес.: не больше {cap:.0f} номеро-месяцев, это {cap / GAP_MONTHS:.0%} зазора")

print("\n== Пилот: доля базы, нужная для сравнения 12 % против 6 % (706 групп, S-25) ==")
print(f"  семьи на начало года 6500: {706 / 6500:.1%}")
print(f"  владельцы на начало года 800: {706 / 800:.1%}")
print(f"  сравнение 12 % против 9 % (3268): семьи {3268 / 6500:.1%}, владельцы {3268 / 800:.0%}")

print("\n== Предельное вложение = прибыль от доп. месяцев минус прямые расходы (ДОПУЩЕНИЕ: 100 руб. на месяц) ==")
for m in (9, 6):
    for d in (0.5, 1.0, 2.0):
        months = fam_groups * fam_n["средне"] * d / 100 * factor(m)
        print(f"  семьи, {m} мес., d={d} п.п.: предел вложений {months * (RATE - 100) / 1e6:.2f} млн руб.")
