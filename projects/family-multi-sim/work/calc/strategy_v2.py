# Дополнение к strategy_plan.py (S-29) по находкам red-team. Модель вклада та же.
# Числа брифа S-1: 279, 285, 12 000 мес., 500 руб., строки таблицы. Всё с пометкой ДОПУЩЕНИЕ проверяется журналом и пилотом.
RATE, COST = 500, 100  # ДОПУЩЕНИЕ: прямые расходы 100 руб. на доп. месяц
BASE, GOAL = 279.0, 285.0
GAP = (GOAL - BASE) * 1e6
GROUPS_AVG = (6500 + 8000) / 2
NUM = GROUPS_AVG * 3  # ДОПУЩЕНИЕ: 3 номера в группе
OWN_NUM = 900 * 2.5  # ДОПУЩЕНИЕ: 2,5 номера у владельца


def kept_rows(numbers, d, start):
    out, kept = [], 0.0
    for m in range(1, 13):
        if m >= start:
            kept += numbers * d / 100
        out.append(kept)
    return out


def chosen(d, v2=True):
    rows = [a + b for a, b in zip(kept_rows(NUM / 2, d, 5), kept_rows(NUM / 2, d, 7))]
    if v2:
        rows = [a + b for a, b in zip(rows, kept_rows(NUM, 0.5, 10))]  # ДОПУЩЕНИЕ: услуга с октября, плюс 0,5 п.п.
    return rows


def mln(months, c=0):
    return months * (RATE - c) / 1e6


print("== 1. Граница решения: снижение оттока, при котором сигнал закрывает зазор 6 млн ==")
unit = sum(chosen(1.0, v2=False))
for c in (0, COST):
    print(f"  прямые расходы {c} руб.: нужно {GAP / (RATE - c):.0f} мес., снижение оттока {GAP / (RATE - c) / unit:.1f} п.п. в месяц")

print("\n== 2. Три пути в одной модели, плановый год ==")
paths = {
    "выбранный путь (сигнал 50 на 50 с мая и июля, услуга с октября)": chosen,
    "сразу услуга для семей на всех группах с июля (вариант 2)": lambda d: kept_rows(NUM, d, 7),
    "пилот владельцев на всех владельцах с июля (вариант 3)": lambda d: kept_rows(OWN_NUM, d, 7),
}
for name, f in paths.items():
    for d in (0.5, 1.0):
        m = sum(f(d))
        print(f"  {name}, d={d} п.п.: {m:.0f} мес., до расходов {mln(m):.2f} млн, после расходов {mln(m, COST):.2f} млн руб.")

print("\n== 3. Владельцы: сигнал о списании с ноября, контрольная часть 20 % ==")
for d in (0.5, 1.0):
    m = sum(kept_rows(OWN_NUM * 0.8, d, 11))
    print(f"  d={d} п.п.: удержано владельцев {950 * 0.8 * d / 100 * 2:.0f}, доп. месяцев номеров {m:.0f}, {mln(m, COST):.2f} млн руб.")
print(f"  владельцев в контрольной части около {950 * 0.2:.0f}, с сигналом около {950 * 0.8:.0f}")

print("\n== 4. Пять строк на конец планового года, владельцы с ноября ==")
for name, d, act_up, actv in (("низкий", 0.5, 0.03, 0.50), ("средний", 1.0, 0.05, 0.52), ("высокий", 2.0, 0.08, 0.55)):
    groups = 8000 + GROUPS_AVG / 2 * d / 2 / 100 * 8 + GROUPS_AVG / 2 * d / 2 / 100 * 6  # ДОПУЩЕНИЕ: отток групп вдвое слабее
    active = groups * (5000 / 8000 + act_up)  # ДОПУЩЕНИЕ: доля активных плюс 3, 5, 8 п.п., расчёта эффекта нет
    own = 1000 + 950 * 0.8 * d / 100 * 2
    profit = BASE + mln(sum(chosen(d, v2=False)), COST)
    print(f"  {name}: прибыль {profit:.1f} млн руб., активных групп {active:.0f}, подключённых групп {groups:.0f}, владельцев {own:.0f}, активация {actv:.0%} (допущение)")

print("\n== 5. Разрыв по строкам и предельная цена привлечения единицы (средний сценарий) ==")
print("  ДОПУЩЕНИЕ: новая группа или новый владелец приносит от 0 до 1 нового номера, он платит в среднем 6 месяцев года")
print("  ДОПУЩЕНИЕ: активированная группа снижает отток своих 3 номеров на 1 п.п. в месяц на 6 месяцев")
price_month = RATE - COST
price_new = 1 * 6 * price_month
price_act = 3 * 1.0 / 100 * (6 * 7 / 2) * price_month
rows = (
    ("прибыль, доп. месяц номера", (GAP - mln(sum(chosen(1.0, v2=False)), COST) * 1e6) / price_month, price_month),
    ("подключённая группа", 12000 - 8254, price_new),
    ("активная группа", 8000 - 5571, price_act),
    ("владелец нескольких номеров", 2000 - (1000 + 950 * 0.8 * 1.0 / 100 * 2), price_new),
)
for name, units, price in rows:
    print(f"  {name}: разрыв {units:.0f} ед., предельная цена до {price:.0f} руб. за единицу, всего до {units * price / 1e6:.2f} млн руб.")
created_q4 = 2805 / 4
print(f"  активация: разрыв 8 п.п. это около {created_q4 * 0.08:.0f} групп из {created_q4:.0f} созданных в 4 квартале, предельная цена до {price_act:.0f} руб. за группу")

print("\n== 6. Второй и третий год (ДОПУЩЕНИЕ: рост групп линейно до 12 000, контроль 5 %, без переноса удержанных номеров) ==")
y1, y3 = 8254, 12000
y2 = (y1 + y3) / 2
PM_Y1, PM_Y2 = 21, 8  # ДОПУЩЕНИЕ: второй год аналитик 3, разработка 3, тестирование 1, дизайнер 1
for d in (0.5, 1.0):
    n2 = (y1 + y2) / 2 * 3 * 0.95
    m2 = n2 * d / 100 * 78
    carry = chosen(d)[-1] * sum(0.98 ** k for k in range(1, 13))  # ДОПУЩЕНИЕ: удержанные в первом году уходят с оттоком 2 % в месяц
    m1 = sum(chosen(d))
    print(f"  d={d} п.п.: второй год {m2:.0f} мес., {mln(m2, COST):.2f} млн, перенос удержанных первого года ещё {mln(carry, COST):.2f} млн руб.")
    for price in (0.15, 0.3):
        total = mln(m1, COST) + mln(m2, COST) - (PM_Y1 + PM_Y2) * price
        print(f"    цена чел.-мес. {price} млн: итог двух лет без переноса {total:+.2f} млн руб.")
print(f"  владельцы: с 1000 до 2000 за два года это плюс 500 в год, {500 / 40000:.2%} доступной базы в год")
